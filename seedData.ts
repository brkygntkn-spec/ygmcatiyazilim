function makeKpis(
  prefix: string,
  baseScore: number,
  dept: string
): KPIItem[] {
  const clamp = (n: number) => Math.max(40, Math.min(100, Math.round(n)));
  const templates: Record<string, [string, string, string, string]> = {
    Operasyon: [
      'Operasyonel SLA Karşılama Oranı',
      'Bölge Şube Hizmet Sürekliliği Endeksi',
      'Süreç İyileştirme ve Maliyet Verimliliği',
      '%',
    ],
    Lojistik: [
      'Sevkiyat Zamanında Teslimat Oranı',
      'Depo Stok Doğruluk ve Envanter Uyumu',
      'Filo ve Tedarik Zinciri Optimizasyonu',
      '%',
    ],
    'İnsan Kaynakları': [
      'Kritik Kadro Doluluk Süresi Hedefi',
      'Çalışan Bağlılığı ve Gelişim Planı Uygulama',
      'Performans ve Kalibrasyon Süreci Tamamlanma',
      '%',
    ],
    'Bilgi Teknolojileri': [
      'Kritik Sistem Kesintisiz Çalışma (Uptime)',
      'Dijital Dönüşüm Sprint Teslimat Oranı',
      'Bilgi Güvenliği ve Sızma Testi Uyumu',
      '%',
    ],
    Finans: [
      'Bütçe Sapma Kontrol ve Raporlama Doğruluğu',
      'Nakit Akışı ve Ödeme Döngüsü Verimliliği',
      'İç Denetim Bulgusu Kapatma Oranı',
      '%',
    ],
    'Saha Koordinasyon': [
      'Acil Müdahale ve Saha Hazırlık Süresi',
      'Bölgesel Ekip Koordinasyon Denetim Puanı',
      'Saha Raporlama ve Envanter Güncelliği',
      '%',
    ],
  };

  const t = templates[dept] || templates.Operasyon;
  const s1 = clamp(baseScore + 3);
  const s2 = clamp(baseScore - 2);
  const s3 = clamp(baseScore + 1);

  return [
    {
      id: `${prefix}-k1`,
      title: t[0],
      category: 'KPI',
      weight: 40,
      targetValue: 95,
      actualValue: Math.round((95 * s1) / 100),
      unit: t[3],
      selfScore: clamp(s1 + 3),
      managerScore: s1,
      managerComment: s1 >= 85 ? 'Hedefin üzerinde istikrarlı gerçekleşme sağlandı.' : 'Dönem içi operasyonel dalgalanmalara rağmen temel standart korundu.',
    },
    {
      id: `${prefix}-k2`,
      title: t[1],
      category: 'OKR',
      weight: 35,
      targetValue: 90,
      actualValue: Math.round((90 * s2) / 100),
      unit: t[3],
      selfScore: clamp(s2 + 4),
      managerScore: s2,
      managerComment: s2 >= 80 ? 'Birimler arası koordinasyon katkısı güçlü.' : 'Ara dönem takip aksiyonları ile gelişim desteklenmeli.',
    },
    {
      id: `${prefix}-k3`,
      title: t[2],
      category: 'KPI',
      weight: 25,
      targetValue: 100,
      actualValue: Math.round(s3),
      unit: 'Puan',
      selfScore: clamp(s3 + 2),
      managerScore: s3,
      managerComment: 'Kurumsal kalite ve raporlama takvimine uyumlu ilerleme.',
    },
  ];
}

function makePerfRecords(
  empId: string,
  dept: string,
  score2026End: number,
  stage2026End: PerformanceWorkflowStage,
  calibrated?: { score: number; note: string }
): Record<EvaluationPeriod, {
  period: EvaluationPeriod;
  stage: PerformanceWorkflowStage;
  kpis: KPIItem[];
  calculatedScore: number;
  calibratedScore?: number;
  calibrationNote?: string;
  managerSummary: string;
  updatedAt: string;
}> {
  const midScore = Math.max(45, Math.min(98, score2026End - 3));
  const prevYearScore = Math.max(48, Math.min(96, score2026End - 5));

  const kpisEnd = makeKpis(`${empId}-26y`, score2026End, dept);
  const calcEnd = Math.round(
    kpisEnd.reduce((s, k) => s + k.managerScore * (k.weight / 100), 0) * 10
  ) / 10;

  const kpisMid = makeKpis(`${empId}-26a`, midScore, dept);
  const calcMid = Math.round(
    kpisMid.reduce((s, k) => s + k.managerScore * (k.weight / 100), 0) * 10
  ) / 10;

  const kpisPrev = makeKpis(`${empId}-25y`, prevYearScore, dept);
  const calcPrev = Math.round(
    kpisPrev.reduce((s, k) => s + k.managerScore * (k.weight / 100), 0) * 10
  ) / 10;

  return {
    '2026 Yıl Sonu Dönemi': {
      period: '2026 Yıl Sonu Dönemi',
      stage: stage2026End,
      kpis: kpisEnd,
      calculatedScore: calcEnd,
      calibratedScore: calibrated?.score,
      calibrationNote: calibrated?.note,
      managerSummary:
        score2026End >= 86
          ? 'Dönem boyunca yüksek sorumluluk bilinci ve güçlü sonuç üretimi sergiledi. Bir üst rol sorumluluklarına hazır.'
          : score2026End >= 72
          ? 'Görev tanımı kapsamındaki hedefleri istikrarlı biçimde karşıladı; çapraz birim projelerinde etkinliği artırılabilir.'
          : 'Hedef gerçekleşme hızında iyileştirme gerekiyor; yapılandırılmış koçluk ve yakın takip planlandı.',
      updatedAt: '2026-11-18',
    },
    '2026 Ara Dönem': {
      period: '2026 Ara Dönem',
      stage: 'Kalibrasyon & Kesinleşme',
      kpis: kpisMid,
      calculatedScore: calcMid,
      managerSummary: 'Ara dönem değerlendirme görüşmesi tamamlandı ve ikinci yarı aksiyonları belirlendi.',
      updatedAt: '2026-06-28',
    },
    '2025 Yıl Sonu Dönemi': {
      period: '2025 Yıl Sonu Dönemi',
      stage: 'Kalibrasyon & Kesinleşme',
      kpis: kpisPrev,
      calculatedScore: calcPrev,
      managerSummary: '2025 yılı performans döngüsü kalibrasyon kurulu tarafından onaylanarak kesinleştirildi.',
      updatedAt: '2025-12-22',
    },
  };
}

